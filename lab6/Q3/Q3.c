#include <LPC17xx.h>

#define LEDS 0x00000FF0

void delay_1sec(void)
{
    volatile unsigned int i;

    for(i = 0; i < 1000000; i++);
}

void show(unsigned int pattern)
{
    LPC_GPIO0->FIOCLR = LEDS;
    LPC_GPIO0->FIOSET = pattern;
    delay_1sec();
}

int main(void)
{
    SystemInit();

    /* P0.4 - P0.11 as output */
    LPC_GPIO0->FIODIR |= LEDS;

    /* All OFF */
    LPC_GPIO0->FIOCLR = LEDS;


    while(1)
    {
        /* =====================================
           PHASE 1 - OUTSIDE TO INSIDE
           ===================================== */

        show((1<<4) | (1<<11));
        show((1<<5) | (1<<10));
        show((1<<6) | (1<<9));
        show((1<<7) | (1<<8));


        /* =====================================
           PHASE 2 - INSIDE TO OUTSIDE
           ===================================== */

        show((1<<7) | (1<<8));
        show((1<<6) | (1<<9));
        show((1<<5) | (1<<10));
        show((1<<4) | (1<<11));


        /* =====================================
           PHASE 3 - EXPANDING
           ===================================== */

        show((1<<7) | (1<<8));

        show((1<<6) | (1<<7) |
             (1<<8) | (1<<9));

        show((1<<5) | (1<<6) |
             (1<<7) | (1<<8) |
             (1<<9) | (1<<10));

        show((1<<4) | (1<<5) |
             (1<<6) | (1<<7) |
             (1<<8) | (1<<9) |
             (1<<10) | (1<<11));


        /* =====================================
           PHASE 4 - CONTRACTING
           ===================================== */

        show((1<<5) | (1<<6) |
             (1<<7) | (1<<8) |
             (1<<9) | (1<<10));

        show((1<<6) | (1<<7) |
             (1<<8) | (1<<9));

        show((1<<7) | (1<<8));


        /* =====================================
           PHASE 5 - ALTERNATING
           ===================================== */

        show((1<<4) | (1<<6) |
             (1<<8) | (1<<10));

        show((1<<5) | (1<<7) |
             (1<<9) | (1<<11));

        show((1<<4) | (1<<6) |
             (1<<8) | (1<<10));

        show((1<<5) | (1<<7) |
             (1<<9) | (1<<11));


        /* =====================================
           PHASE 6 - CROSS PATTERN
           ===================================== */

        show((1<<4) | (1<<7) |
             (1<<8) | (1<<11));

        show((1<<5) | (1<<6) |
             (1<<9) | (1<<10));

        show((1<<4) | (1<<7) |
             (1<<8) | (1<<11));

        show((1<<5) | (1<<6) |
             (1<<9) | (1<<10));


        /* =====================================
           PHASE 7 - ALL ON/OFF
           ===================================== */

        show(LEDS);

        LPC_GPIO0->FIOCLR = LEDS;
        delay_1sec();

        show(LEDS);

        LPC_GPIO0->FIOCLR = LEDS;
        delay_1sec();


        /* =====================================
           PHASE 8 - FINAL WAVE
           ===================================== */

        show((1<<4));

        show((1<<4) | (1<<5));

        show((1<<4) | (1<<5) |
             (1<<6));

        show((1<<4) | (1<<5) |
             (1<<6) | (1<<7));

        show((1<<4) | (1<<5) |
             (1<<6) | (1<<7) |
             (1<<8));

        show((1<<4) | (1<<5) |
             (1<<6) | (1<<7) |
             (1<<8) | (1<<9));

        show((1<<4) | (1<<5) |
             (1<<6) | (1<<7) |
             (1<<8) | (1<<9) |
             (1<<10));

        show(LEDS);


        /* Pause before repeating */

        LPC_GPIO0->FIOCLR = LEDS;
        delay_1sec();
        delay_1sec();
    }
}
